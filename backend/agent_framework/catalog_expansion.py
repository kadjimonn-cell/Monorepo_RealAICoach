    permissions = ["llm.complete"]
    if "db_read" in tools:
        permissions.append("data.read")
    if "http_fetch" in tools:
        permissions.append("network.fetch")
    return {
        "agent_key": key, "name": name, "role": role, "category": category,
        "subcategory": subcategory, "description": description,
        "system_prompt": system_prompt, "provider": "openai", "model": "gpt-4o",
        "allowed_tools": tools, "tags": tags or [], "feature_mappings": features,
        "permissions": permissions, "availability": availability, "status": status,
        "dependencies": deps or [], "config_profile": dict(DEFAULT_CONFIG_PROFILE),
    }


