def _agent(key, name, role, category, description, system_prompt, tools=None, tags=None):
    tools = tools or ["template_render"]
    permissions = ["llm.complete"]
    if "db_read" in tools:
        permissions.append("data.read")
    if "http_fetch" in tools:
        permissions.append("network.fetch")
    return {
        "agent_key": key,
        "name": name,
        "role": role,
        "category": category,
        "subcategory": role,
        "description": description,
        "system_prompt": system_prompt,
        "provider": "openai",
        "model": "gpt-4o",
        "allowed_tools": tools,
        "tags": tags or [],
        "feature_mappings": list(_CATEGORY_FEATURES.get(category, [])),
        "permissions": permissions,
        "availability": "user" if category == CATEGORY_COACHING else "global",
        "status": "active",
        "dependencies": [],
        "config_profile": {"temperature": 0.4, "max_tokens": 1400},
    }


